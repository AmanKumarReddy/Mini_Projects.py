            "Water is one of the rare compounds that expands when it freezes, which allows ice to float and preserves aquatic life during winter.",
            "The human brain contains roughly eighty-six billion neurons, generating enough electrical power to light up a small, low-wattage LED bulb.",
            "If you uncoiled all the strands of DNA inside a single human body, the total length would stretch from Earth to Pluto and back.",
            "Absolute depth in the ocean is found at the Mariana Trench, a location deeper than Mount Everest is tall.",
